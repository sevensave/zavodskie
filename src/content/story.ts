export interface StorySpec {
  key: string
  day: number
  /** Место в очереди, с нуля. */
  at: number
  /** Дело приходит только при этом условии. */
  when?: (x: StoryCtx) => boolean
  who: PersonId
  model: string
  device: DeviceTruth
  owner: OwnerTruth
  flaw?: Flaw
  complaint: string
  talk: string[]
  /** Речь самотеста для отклонившихся. Остальным — по модели. */
  diag?: string
  excuse?: string
  /** Человек на проверке: на стойке конвойный прибор этой модели. */
  escort?: string
  /** Конверт; меченый он, если посетитель — агент ОБ. */
  bribe?: { amount: number; wants: Verdict }
  /** Кэш, когда посетитель подходит к окну. */
  arrive?: KeshLine
  /** Кэш после штампа. */
  react?: { spared?: KeshLine; reset?: KeshLine; security?: KeshLine; junk?: KeshLine; other?: KeshLine }
  /** На этом деле очередь кончается (финал). */
  last?: boolean
}

const spared = (v: Verdict | undefined) => v === 'return' || v === 'refuse' || v === 'junk'
const not = (id: RegularId) => (x: StoryCtx) => x.agent !== id
const is = (id: RegularId) => (x: StoryCtx) => x.agent === id
const corp = (x: StoryCtx) => x.branch !== 'machines'
const machines = (x: StoryCtx) => x.branch === 'machines'
const plus = (x: StoryCtx) => !!x.flags.plus

